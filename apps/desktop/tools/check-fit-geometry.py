"""核对"窗口贴合立绘 + 原地旋转"的可行性 —— 先证明再写代码。

已知（实测，画布 240x240）：
    立绘可见包围盒 x0=96 y0=114 w=155 h=177
    （注意：不是居中！左边空 96、右边空 84；上边空 114、下边空 63）

方案：把画布整体偏移，让**立绘中心**落到窗口中心；窗口取"能装下旋转后立绘"的
最小边长。这样窗口边 == 立绘的旋转外接边，贴边判定不需要任何估算留白。

约束（用户明确要求）：
    ① 立绘不放大、不缩小（「全身比例不变」）
    ② 旋转后不被裁切
    ③ 窗口尽量小（贴合）
"""

CANVAS = 240
X0, Y0, W, H = 96, 114, 155, 177

cx = X0 + W / 2
cy = Y0 + H / 2
print(f"  立绘中心在画布坐标 ({cx:.1f}, {cy:.1f})；画布中心 (120, 120)")
print(f"  -> 需要把画布平移 ({120 - cx:+.1f}, {120 - cy:+.1f}) 让立绘居中")
print()

# 旋转 45° 后立绘的外接边长
diag = (W + H) * (2**0.5) / 2
print(f"  立绘 {W}x{H} 旋转 45° 后外接 = ({W}+{H})*√2/2 = {diag:.1f}")
print()

for name, side in [
    ("窗口 = 画布 240", 240),
    ("窗口 = 旋转外接", int(diag) + 1),
    ("窗口 = 立绘最大边 + 余量", H + 12),
]:
    # 要让立绘恰好占满窗口边长 side，需要缩放多少？
    scale_needed = side / diag
    # 立绘在窗口里居中时的留白
    pad = (side - W) / 2
    ok_rot = side >= diag
    ok_noscale = abs(scale_needed - 1.0) < 0.02
    print(f"  {name:<24} 边长 {side:>3}")
    print(f"      旋转后完整可见: {'是' if ok_rot else '否（会被裁）'}")
    print(f"      比例不变(scale=1): {'是' if ok_noscale else f'否（需要 scale={scale_needed:.2f}）'}")
    print(f"      立绘到窗口边留白: {pad:.1f}px 每侧")
    print()

print("  结论：只有「窗口 >= 旋转外接(235)」才能同时满足不裁切 + 比例不变。")
print("        窗口取 240（= 画布边长）正好；立绘居中后每侧留白 (240-155)/2≈42px。")
print("        贴边判定用 artMargin=42，比现在的 67 更贴合，且是对称的。")
