COLOR_RE = re.compile(r"#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)")


def convert(path: pathlib.Path) -> None:
    text = path.read_text(encoding="utf-8")
    for old, new in MAPPING.items():
        text = text.replace(old, new)
        text = text.replace(old.upper(), new)
    path.write_text(text, encoding="utf-8")

    leftovers = sorted(
        {
            m
            for m in COLOR_RE.findall(text)
            # 新设计语言自身的颜色不算残留
            if m.lower()
            not in {
                "#f5f6f8", "#fafbfc", "#f0f2f5", "#eef0f4", "#ffffff", "#fff",
                "#fbfcfd", "#f3f5f9", "#e4e7ec", "#d3d7de", "#3c4149",
                "#98a0a8", "#5b616b", "#2f6fed", "#22a06b", "#d93843",
                "#b32833", "#c2373f", "#f0a500", "#f5a623", "#e8effd",
                "#d5e2fb", "#e6f4ec", "#1f7a4d", "#fbeaec", "#f5d5d8",
                "#eceef2", "#c2c7ce", "#ffcb2e", "#2a63d4",
            }
        }
    )
    print(f"  {path.name}: 完成；残留未映射颜色 {len(leftovers)} 个")
    for c in leftovers:
        print(f"    {c}")


